// node tools/build_bank.js [N]  → src/bank.js
// Builds the graded puzzle bank: N puzzles (default 300) per variant × grade, plus the Jigsaw layouts they use.
// Every puzzle comes from the same generator the game runs (src/solver.js): 180°-symmetric givens, solvable by logic
// alone, hardest technique exactly the grade. Runs one worker per bucket, two at a time.
const fs=require('fs'), path=require('path'), {fork}=require('child_process');
const {load}=require('../tests/lib.js');
const X=load(['engine.js','solver.js']);
const ROOT=path.join(__dirname,'..'), N=+(process.argv[2]||300), LAYOUTS=48;

if(process.argv[2]==='--worker'){ const [,,,v,gr,n,layoutsJson]=process.argv; const layouts=JSON.parse(fs.readFileSync(layoutsJson,'utf8'));
  const out=[], seen=new Set(), t0=Date.now(); let tries=0;
  for(let i=0;out.length<+n;i++){ const seed=`B|${v}|${gr}|${i}`; let li=null, regions=null;
    if(v==='jigsaw'){ li=Math.floor(X.rngFor(seed+'|L')()*layouts.length); regions=layouts[li]; }
    const it=X.genPuzzle(v,gr,seed,regions); let r; do{ r=it.next(); }while(!r.done); tries++;
    const p=r.value; if(!p||seen.has(p.givens)) continue; seen.add(p.givens);
    out.push({e:X.encPuzzle(p.givens,li),count:p.count,hardest:p.hardest,par:p.par}); }
  process.send({v,gr,out,tries,ms:Date.now()-t0}); process.exit(0); }

// ---- master ----
const t0=Date.now();
const layouts=[]; { const rng=X.rngFor('SUDJ|layouts'); while(layouts.length<LAYOUTS){ const r=X.genLayout(rng); if(r&&!layouts.includes(r)) layouts.push(r); } }
const lj=path.join(require('os').tmpdir(),'sudoku_layouts.json'); fs.writeFileSync(lj,JSON.stringify(layouts));
const jobs=[]; for(const v of X.VKEYS) for(const gr of X.gradesFor(v)) jobs.push([v,gr]);
// the slow ones first
const cost={'mini|normal':9,'jigsaw|expert':8,'jigsaw|hard':7,'classic|expert':6,'jigsaw|normal':5,'classic|hard':5,'classic|normal':4}; jobs.sort((a,b)=>(cost[b.join('|')]||0)-(cost[a.join('|')]||0));
const res={}; let running=0, next=0;
function launch(){ while(running<2&&next<jobs.length){ const [v,gr]=jobs[next++]; running++;
    const w=fork(__filename,['--worker',v,gr,String(N),lj]); w.on('message',m=>{ res[m.v+'|'+m.gr]=m; console.log(`  ${m.v} ${m.gr}: ${m.out.length} puzzles from ${m.tries} tries in ${(m.ms/1000).toFixed(1)} s`); });
    w.on('exit',()=>{ running--; if(next<jobs.length) launch(); else if(!running) finish(); }); } }
function finish(){ const med=a=>{ const b=a.slice().sort((x,y)=>x-y); return b[b.length>>1]; };
  const info={built:new Date().toISOString().slice(0,10),n:{},givens:{},par:{},hardest:{}}; let raw='';
  for(const [v,gr] of jobs.slice().sort((a,b)=>X.VKEYS.indexOf(a[0])-X.VKEYS.indexOf(b[0])||X.GRADES.indexOf(a[1])-X.GRADES.indexOf(b[1]))){ const k=v+'|'+gr, m=res[k];
    raw+=` '${k}':'${m.out.map(o=>o.e).join(',')}',\n`;
    const cs=m.out.map(o=>o.count), ps=m.out.map(o=>o.par), hs={}; m.out.forEach(o=>hs[o.hardest]=(hs[o.hardest]||0)+1);
    info.n[k]=m.out.length; info.givens[k]=[Math.min(...cs),med(cs),Math.max(...cs)]; info.par[k]=med(ps); info.hardest[k]=hs; }
  const js=`// Generated by tools/build_bank.js on ${info.built}. Do not edit by hand.
// Graded puzzles per variant × grade (see engine.js encPuzzle for the format) and the Jigsaw layouts they use.
const BANK_REGIONS=${JSON.stringify(layouts)};
const BANK_RAW={
${raw}};
const BANK_INFO=${JSON.stringify(info)};
`;
  fs.writeFileSync(path.join(ROOT,'src','bank.js'),js);
  console.log(`src/bank.js: ${(js.length/1024).toFixed(1)} KB in ${((Date.now()-t0)/1000).toFixed(0)} s`);
  for(const k in info.n) console.log(`  ${k.padEnd(16)} n ${info.n[k]}  givens ${info.givens[k].join('/')}  par median ${Math.floor(info.par[k]/60)}:${String(info.par[k]%60).padStart(2,'0')}  ${JSON.stringify(info.hardest[k])}`); }
launch();
