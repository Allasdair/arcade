// node tools/build_bank.js [N]  →  src/bank.js (+ tests/bank_solutions.json.gz, the stored solutions the tests replay)
// For each draw mode, deals SOL1|0, SOL1|1, … are solved by the perfect-knowledge solver; deals it can't prove within
// its node limit are thrown away. Each kept deal is graded by the blind bot (20 plays), given par moves (the shortest
// proven win found: the best of several solver runs or the bot's shortest win, + 15% slack, rounded up), and the fewest
// passes it needs (1, 3 or unlimited). The first 500 deals of each mode also get an Open deck grade.
// Runs on all CPU cores with worker_threads. Takes ~15–25 min on 2 cores.
const {Worker,isMainThread,parentPort,workerData}=require('worker_threads');
const path=require('path'), fs=require('fs'), zlib=require('zlib');
const ROOT=path.join(__dirname,'..');
const TARGET=2000, OPEN_PER=500, LIMIT=40000, JITTER=6, SLACK=1.15;
function work(draw,n,X){ const seed=X.dealSeed(n), cfg={draw}, g=c=>X.newGame(seed,Object.assign({draw},c||{}));
  const a=X.solveAll(g(),{limit:LIMIT}); if(a.status!=='win') return null;
  let best=a.solution;
  for(let r=0;r<JITTER;r++){ const b=X.solveAll(g(),{limit:6000,jitter:1,seed:'p'+r}); if(b.status==='win'&&b.cost<best.length) best=b.solution; }
  const gr=X.gradeRate(seed,cfg,20); if(gr.best&&gr.best.length<best.length) best=gr.best;
  // check the stored solution really wins
  const t=g(); X.playActions(t,best); if(!(t.won||X.canAutoComplete(t))) throw new Error('solution fails '+draw+' '+n);
  let passes=0; if(X.solveAll(g({passes:1}),{limit:15000}).status==='win') passes=1; else if(X.solveAll(g({passes:3}),{limit:15000}).status==='win') passes=3;
  const par=Math.ceil(best.length*SLACK);
  const open=n<OPEN_PER*2?X.gradeRate(seed,{draw,open:true},20).rate:null;
  return {n,draw,grade:X.gradeOf(gr.rate),rate:gr.rate,avg:gr.avgMoves,par,len:best.length,passes,open,sol:best.join(' ')}; }
if(!isMainThread){ const X=require(path.join(ROOT,'tests','lib.js')).load(['engine.js','solver.js']);
  parentPort.on('message',m=>{ if(m===null) process.exit(0); parentPort.postMessage({key:m,r:work(m.draw,m.n,X)}); }); }
else { const N=+process.argv[2]||3400, cores=require('os').cpus().length, res={1:{},3:{}}; let next={1:0,3:0}, doneN=0, t0=Date.now(), active=0;
  const jobs=[]; for(let n=0;n<N;n++) for(const d of [1,3]) jobs.push({draw:d,n}); let ji=0;
  const ws=[]; for(let c=0;c<cores;c++){ const w=new Worker(__filename); ws.push(w); active++;
    const feed=()=>{ if(ji<jobs.length) w.postMessage(jobs[ji++]); else { w.postMessage(null); if(--active===0) finish(); } };
    w.on('message',({key,r})=>{ res[key.draw][key.n]=r; if(++doneN%200===0) console.log(`${doneN}/${jobs.length} deals, ${((Date.now()-t0)/1000).toFixed(0)} s`); feed(); });
    w.on('error',e=>{ console.error(e); process.exit(1); }); feed(); }
  function finish(){ const out={}, sols={}, stats={};
    for(const d of [1,3]){ const kept=Object.keys(res[d]).map(Number).sort((a,b)=>a-b).map(n=>res[d][n]).filter(Boolean).slice(0,TARGET);
      if(kept.length<TARGET) console.log(`WARNING: draw ${d} has only ${kept.length} winnable deals; raise N`);
      out[d]=kept; for(const k of kept) sols[d+'|'+k.n]=k.sol; }
    const G=['easy','medium','hard','expert'];
    // par time: seconds per par move, by draw mode and grade, from the bot (1.2 s per bot move, scaled by how many moves
    // the bot's wins take compared with par). Grades the bot never wins borrow the next easier grade's figure.
    const spm={};
    for(const d of [1,3]){ spm[d]={}; let prev=1.4; for(const g of G){ const xs=out[d].filter(k=>k.grade===g&&k.avg>0).map(k=>k.avg/k.par);
      const v=xs.length>=5?1.2*xs.reduce((a,b)=>a+b,0)/xs.length:prev; spm[d][g]=+v.toFixed(3); prev=v; }
      stats[d]={total:out[d].length,grades:G.map(g=>out[d].filter(k=>k.grade===g).length),pass1:out[d].filter(k=>k.passes===1).length,pass3:out[d].filter(k=>k.passes===3).length,
        par:{min:Math.min(...out[d].map(k=>k.par)),max:Math.max(...out[d].map(k=>k.par)),avg:+(out[d].reduce((a,k)=>a+k.par,0)/out[d].length).toFixed(1)},
        open:G.map(g=>out[d].slice(0,OPEN_PER).filter(k=>X0.gradeOf(k.open)===g).length)}; }
    const enc=k=>k.n.toString(36).padStart(3,'0')+G.indexOf(k.grade)+k.par.toString(36).padStart(2,'0')+k.passes;
    const encO=k=>k.n.toString(36).padStart(3,'0')+G.indexOf(X0.gradeOf(k.open));
    const js=`// Generated by tools/build_bank.js — do not edit. ${new Date().toISOString().slice(0,10)}.
// Every deal here is proven winnable by the solver (its solution is replayed by the tests).
// Entry: deal number (3 base-36 chars, seed SOL1|n), grade (0 Easy, 1 Medium, 2 Hard, 3 Expert), par moves (2 base-36
// chars), fewest passes needed (1, 3, or 0 = unlimited). Open deck: deal number + its Open deck grade.
// Grades (blind bot, 20 plays): Easy ≥ 75% wins, Medium 50–75%, Hard 25–50%, Expert < 25%.
const BANK_RAW={1:'${out[1].map(enc).join('')}',3:'${out[3].map(enc).join('')}'};
const BANK_OPEN_RAW={1:'${out[1].slice(0,OPEN_PER).map(encO).join('')}',3:'${out[3].slice(0,OPEN_PER).map(encO).join('')}'};
// par time = par moves × seconds per move (by draw mode and grade), rounded up to 5 s
const PAR_SPM=${JSON.stringify(spm)};
const BANK_STATS=${JSON.stringify(stats)};
`;
    fs.writeFileSync(path.join(ROOT,'src','bank.js'),js);
    fs.writeFileSync(path.join(ROOT,'tests','bank_solutions.json.gz'),zlib.gzipSync(JSON.stringify(sols)));
    console.log('bank.js',(js.length/1024).toFixed(1),'KB'); console.log(JSON.stringify(stats,null,1)); console.log('spm',JSON.stringify(spm));
    console.log('total',((Date.now()-t0)/60000).toFixed(1),'min'); process.exit(0); }
  var X0=require(path.join(ROOT,'tests','lib.js')).load(['engine.js','solver.js']); }
